'use strict';
// Builds realistic sample Bambu-style 3MF files (used by tests, mock mode and the demo build).
const AdmZip = require('adm-zip');

function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;'); }

function cubeMesh(size = 20) {
  const s = size;
  const v = [[0,0,0],[s,0,0],[s,s,0],[0,s,0],[0,0,s],[s,0,s],[s,s,s],[0,s,s]];
  const t = [[0,2,1],[0,3,2],[4,5,6],[4,6,7],[0,1,5],[0,5,4],[1,2,6],[1,6,5],[2,3,7],[2,7,6],[3,0,4],[3,4,7]];
  return `<mesh><vertices>${v.map(p => `<vertex x="${p[0]}" y="${p[1]}" z="${p[2]}"/>`).join('')}</vertices>` +
    `<triangles>${t.map(p => `<triangle v1="${p[0]}" v2="${p[1]}" v3="${p[2]}"/>`).join('')}</triangles></mesh>`;
}

/**
 * opts: { name, plate=1, includeMesh, thumbnail (Buffer png), predictionSeconds, filaments:[{type,color,grams,meters,settingsId}],
 *         layerHeight, infill, pattern, supports, outerWallSpeed, nozzleTemp, bedTemp, printerModel, gcodeKb }
 */
function buildSample3mf(o) {
  const plate = o.plate || 1;
  const zip = new AdmZip();
  const fil = o.filaments && o.filaments.length ? o.filaments : [{ type: 'PLA', color: '#000000', grams: 10, meters: 3.3 }];
  zip.addFile('[Content_Types].xml', Buffer.from('<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/><Default Extension="png" ContentType="image/png"/><Default Extension="gcode" ContentType="text/x.gcode"/></Types>'));
  zip.addFile('_rels/.rels', Buffer.from('<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel-1" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>'));
  const objXml = o.includeMesh
    ? `<resources><object id="1" type="model">${cubeMesh()}</object></resources><build><item objectid="1"/></build>`
    : '<resources/><build/>';
  zip.addFile('3D/3dmodel.model', Buffer.from(`<?xml version="1.0" encoding="UTF-8"?><model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><metadata name="Title">${esc(o.name)}</metadata><metadata name="Application">BambuStudio-01.10.01.50</metadata>${objXml}</model>`));
  const filXml = fil.map((f, i) => `<filament id="${i + 1}" tray_info_idx="GFA00" type="${esc(f.type)}" color="${esc(f.color)}" used_m="${f.meters}" used_g="${f.grams}" />`).join('\n    ');
  const totalG = fil.reduce((a, f) => a + f.grams, 0);
  zip.addFile('Metadata/slice_info.config', Buffer.from(`<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header><header_item key="X-BBL-Client-Type" value="slicer"/><header_item key="X-BBL-Client-Version" value="01.10.01.50"/></header>
  <plate>
    <metadata key="index" value="${plate}"/>
    <metadata key="printer_model_id" value="BL-P001"/>
    <metadata key="nozzle_diameters" value="0.4"/>
    <metadata key="prediction" value="${o.predictionSeconds || 1800}"/>
    <metadata key="weight" value="${totalG.toFixed(2)}"/>
    <object identify_id="101" name="${esc(o.name)}.stl" skipped="false" />
    ${filXml}
  </plate>
</config>`));
  const ps = {
    printer_model: o.printerModel || 'Bambu Lab X1 Carbon',
    printer_settings_id: 'Bambu Lab X1 Carbon 0.4 nozzle',
    print_settings_id: `${(o.layerHeight || 0.2).toFixed(2)}mm Standard @BBL X1C`,
    layer_height: String(o.layerHeight || 0.2),
    sparse_infill_density: o.infill || '15%',
    sparse_infill_pattern: o.pattern || 'grid',
    wall_loops: String(o.walls || 2),
    enable_support: o.supports && o.supports !== 'none' ? '1' : '0',
    support_type: o.supports && o.supports !== 'none' ? o.supports : 'normal(auto)',
    outer_wall_speed: [String(o.outerWallSpeed || 200)],
    inner_wall_speed: [String((o.outerWallSpeed || 200) + 100)],
    sparse_infill_speed: [String(270)],
    travel_speed: [String(500)],
    nozzle_temperature: fil.map(() => String(o.nozzleTemp || 220)),
    curr_bed_type: 'Textured PEI Plate',
    textured_plate_temp: fil.map(() => String(o.bedTemp || 55)),
    hot_plate_temp: fil.map(() => String(o.bedTemp || 55)),
    filament_type: fil.map(f => f.type),
    filament_colour: fil.map(f => f.color),
    filament_settings_id: fil.map(f => f.settingsId || `Bambu ${f.type} Basic @BBL X1C`),
  };
  zip.addFile('Metadata/project_settings.config', Buffer.from(JSON.stringify(ps, null, 2)));
  if (o.thumbnail) {
    zip.addFile(`Metadata/plate_${plate}.png`, o.thumbnail);
    zip.addFile(`Metadata/plate_${plate}_small.png`, o.thumbnail);
  }
  const lines = [`; HEADER_BLOCK_START`, `; generated by sample3mf for ${o.name}`, `; total estimated time: ${o.predictionSeconds || 1800}s`, `; HEADER_BLOCK_END`];
  const kb = o.gcodeKb || 8;
  let g = lines.join('\n') + '\n';
  for (let i = 0; g.length < kb * 1024; i++) g += `G1 X${(i * 7) % 250} Y${(i * 13) % 250} E${(i * 0.031).toFixed(3)}\n`;
  zip.addFile(`Metadata/plate_${plate}.gcode`, Buffer.from(g));
  zip.addFile(`Metadata/plate_${plate}.gcode.md5`, Buffer.from(require('crypto').createHash('md5').update(g).digest('hex').toUpperCase()));
  return zip.toBuffer();
}

module.exports = { buildSample3mf };
